  foreach table_name in array array[
    'categories','tags','collections','products','product_images','promotions',
    'promotion_products','promotion_categories','promotion_collections','subscribers',
    'site_header','header_links','hero_section','hero_ctas','hero_stats','about_section',
    'about_stats','about_values','newsletter_section','footer_section',
    'footer_link_groups','footer_links','footer_social_links'
