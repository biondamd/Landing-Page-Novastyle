-- 3 · Vista pública con variantes ---------------------------------------------
-- Añade sizes/colors como arrays JSON, ordenados. El resto de la vista se
-- mantiene igual que en la migración original.

create or replace view public.public_products_view as
select
  p.id,
  p.name,
  p.slug,
  p.price,
  p.color,
  p.description,
  p.sold_out,
  c.name as category_name,
  c.slug as category_slug,
  col.id as collection_id,
  col.name as collection_name,
  col.slug as collection_slug,
  t.name as tag_name,
  coalesce(primary_image.image_url, first_image.image_url) as image_url,
  promo.percentage as promotion_percentage,
  case
    when promo.percentage is null then null
    else round(p.price * (100 - promo.percentage) / 100, 2)
  end as discounted_price,
  coalesce(
    (
      select json_agg(json_build_object('label', s.label, 'available', s.available)
                      order by s.display_order, s.id)
      from public.product_sizes s
      where s.product_id = p.id
    ),
    '[]'::json
  ) as sizes,
  coalesce(
    (
      select json_agg(json_build_object('label', cc.label, 'available', cc.available, 'swatch', cc.swatch)
                      order by cc.display_order, cc.id)
      from public.product_colors cc
      where cc.product_id = p.id
    ),
    '[]'::json
  ) as colors
from public.products p
join public.categories c on c.id = p.category_id and c.status = 'published'
left join public.collections col on col.id = p.collection_id and col.status = 'published'
left join public.tags t on t.id = p.tag_id and t.status = 'published'
left join lateral (
  select pi.image_url
  from public.product_images pi
  where pi.product_id = p.id and pi.is_primary
  limit 1
) primary_image on true
left join lateral (
  select pi.image_url
  from public.product_images pi
  where pi.product_id = p.id
  order by pi.display_order, pi.id
  limit 1
) first_image on true
left join lateral (
  select pr.percentage
  from public.promotions pr
  where pr.status = 'published'
    and now() between pr.starts_at and pr.ends_at
    and (
      (pr.scope = 'product' and exists (
        select 1 from public.promotion_products pp
        where pp.promotion_id = pr.id and pp.product_id = p.id
      ))
      or (pr.scope = 'category' and exists (
        select 1 from public.promotion_categories pc
        where pc.promotion_id = pr.id and pc.category_id = p.category_id
      ))
      or (pr.scope = 'collection' and p.collection_id is not null and exists (
        select 1 from public.promotion_collections pcl
        where pcl.promotion_id = pr.id and pcl.collection_id = p.collection_id
      ))
    )
  order by
    case pr.scope when 'product' then 1 when 'collection' then 2 else 3 end,
    pr.percentage desc
  limit 1
) promo on true
where p.status = 'published';

