-- Novastyle · variantes de producto (tallas/colores con disponibilidad) y
-- lectura pública del contenido del CMS.
--
-- Dos cosas:
--   1. Tablas product_sizes / product_colors editables desde el panel, expuestas
--      en public_products_view para que la landing muestre la ficha de detalle.
--   2. Políticas de lectura pública que le faltaban a las tablas de contenido
--      (cabecera, hero, nosotras, newsletter, footer). Sin ellas la landing —que
--      lee con la clave anónima— recibía filas vacías y, por ejemplo, el menú de
--      navegación se quedaba sin enlaces.

-- 1 · Tablas de variantes -----------------------------------------------------

create table if not exists public.product_sizes (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  label text not null,
  available boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.product_colors (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  label text not null,
  swatch text,
  available boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists product_sizes_product_idx on public.product_sizes(product_id, display_order);
create index if not exists product_colors_product_idx on public.product_colors(product_id, display_order);

alter table public.product_sizes enable row level security;
alter table public.product_colors enable row level security;

-- Lectura pública solo de variantes de productos publicados.
create policy "public read sizes of published products" on public.product_sizes
  for select using (
    exists (select 1 from public.products p where p.id = product_id and p.status = 'published')
  );
create policy "public read colors of published products" on public.product_colors
  for select using (
    exists (select 1 from public.products p where p.id = product_id and p.status = 'published')
  );

-- Gestión desde el panel (usuarios autenticados).
create policy "authenticated manage product_sizes" on public.product_sizes
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "authenticated manage product_colors" on public.product_colors
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

